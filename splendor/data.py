# Per-card feature size — (bonus one-hot 5) + (points 1) + (cost 5) = 11
CARD_FEATURE_SIZE = N_GEM_COLORS + 1 + N_GEM_COLORS
# Per-noble feature size — (points 1) + (cost 5) = 6
NOBLE_FEATURE_SIZE = 1 + N_GEM_COLORS


def encode_card(card: tuple[int, int, int, int, int, int, int]) -> list[float]:
    """카드를 길이 11 벡터로 인코딩."""
    bonus, points = card[0], card[1]
    cost = card[2:7]
    one_hot = [0.0] * N_GEM_COLORS
    one_hot[bonus] = 1.0
    return one_hot + [float(points)] + [float(c) for c in cost]


def empty_card_features() -> list[float]:
    return [0.0] * CARD_FEATURE_SIZE


def encode_noble(noble: tuple[int, int, int, int, int]) -> list[float]:
    return [3.0] + [float(c) for c in noble]


def empty_noble_features() -> list[float]:
    return [0.0] * NOBLE_FEATURE_SIZE
